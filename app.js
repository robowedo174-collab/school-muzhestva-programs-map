function getEducationalEventsForQualityAge(quality, ageRange) {
  return educationalEventsData.filter((event) => event.qualityCode === quality.code && eventAppliesToAge(event, ageRange));
}

function eventAppliesToAge(event, ageRange) {
  if (event.ageVariants && event.ageVariants[ageRange]) return true;
  return event.age === ageRange;
}

function getEventVariant(event, ageRange) {
  if (!event.ageVariants || !event.ageVariants[ageRange]) return event;
  return {
    ...event,
    ...event.ageVariants[ageRange]
  };
}

